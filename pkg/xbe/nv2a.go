package xbe

// NV2A push buffer methods that the dashboard render state wrapper emits for simple states,
// from the nouveau and xemu register definitions
var nv097StateNames = map[uint32]string{
	0x0300: "ALPHATESTENABLE", 0x0304: "ALPHABLENDENABLE", 0x0308: "CULLFACEENABLE", 0x030C: "ZENABLE", 0x0310: "DITHERENABLE",
	0x0314: "LIGHTING", 0x0318: "POINTSCALEENABLE", 0x031C: "POINTSPRITEENABLE", 0x0320: "EDGEANTIALIAS", 0x0324: "POLYSMOOTHENABLE",
	0x0328: "VERTEXBLEND", 0x032C: "STENCILENABLE", 0x0330: "POINTOFFSETENABLE", 0x0334: "WIREFRAMEOFFSETENABLE", 0x0338: "SOLIDOFFSETENABLE",
	0x033C: "ALPHAFUNC", 0x0340: "ALPHAREF", 0x0344: "SRCBLEND", 0x0348: "DESTBLEND", 0x034C: "BLENDCOLOR", 0x0350: "BLENDOP",
	0x0354: "ZFUNC", 0x0358: "COLORWRITEENABLE", 0x035C: "ZWRITEENABLE", 0x0360: "STENCILWRITEMASK", 0x0364: "STENCILFUNC",
	0x0368: "STENCILREF", 0x036C: "STENCILMASK", 0x0370: "STENCILFAIL", 0x0374: "STENCILZFAIL", 0x0378: "STENCILPASS",
	0x037C: "SHADEMODE", 0x0384: "POLYGONOFFSETZSLOPESCALE", 0x0388: "POLYGONOFFSETZOFFSET", 0x038C: "FILLMODE", 0x0390: "BACKFILLMODE",
	0x039C: "CULLMODE", 0x03A0: "FRONTFACE", 0x03A4: "NORMALIZENORMALS", 0x09F8: "SWATHWIDTH", 0x17BC: "LOGICOPENABLE", 0x17C0: "LOGICOP",
}

// NV097StateName returns the render state a push buffer method word configures.
func NV097StateName(methodWord uint32) (string, bool) {
	name, ok := nv097StateNames[methodWord&0x1FFF]
	return name, ok
}
