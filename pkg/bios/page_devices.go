// Steps the init table may take before the page treats a loop in it as never ending
const initTableSteps = 1 << 24

// Push buffer words the FIFO runs before the page treats a push buffer as never reaching its put pointer
const pushWordsBeforeStop = 1 << 24

// Bytes an IO window covers and a memory window may cover at most
const (
	ioWindowBytes     = 0x100
	memoryWindowBytes = 0x1000000
)

// Reads of one register of an unmodeled device with no write between before the page stops
const windowReadsBeforeStop = 1 << 16

// The clock the page reads the time of day from and the data the bridge keeps across loads
const (
	storedEEPROM = "eeprom"
	storedSector = "sector:"
)

