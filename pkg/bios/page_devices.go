// The stall export spun on the real clock for the microseconds its argument holds, each turn of the spin a step
// the interrupts cut into like any block, the return removing what the export's own return removes
func (e *emitter) writeStall() {
	e.js("// ---- the stall ----")
	e.js("function stall() { const s = TABLES.hardware.stall, until = bridge.now() + ld32((ESP + 4 + 4 * s.argument) >>> 0) / 1000; const spin = () => bridge.now() < until ? step(s.entry, spin) : stallReturn(s.cleanup); return spin(); }")
	e.js("function stallReturn(cleanup) { const ret = pop(); ESP = (ESP + cleanup) >>> 0; return go(ret); }")
	e.js("HOOKS.set(TABLES.hardware.stall.entry, stall);")
}
